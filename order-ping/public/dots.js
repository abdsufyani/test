// يرسم رقم الطلب بشكل نقاط (5x7) — مشترك بين صفحة العميل ولوحة الكاشير
(function () {
  const FONT = {
    '0': ['01110', '10001', '10011', '10101', '11001', '10001', '01110'],
    '1': ['00100', '01100', '00100', '00100', '00100', '00100', '01110'],
    '2': ['01110', '10001', '00001', '00010', '00100', '01000', '11111'],
    '3': ['11111', '00010', '00100', '00010', '00001', '10001', '01110'],
    '4': ['00010', '00110', '01010', '10010', '11111', '00010', '00010'],
    '5': ['11111', '10000', '11110', '00001', '00001', '10001', '01110'],
    '6': ['00110', '01000', '10000', '11110', '10001', '10001', '01110'],
    '7': ['11111', '00001', '00010', '00100', '01000', '01000', '01000'],
    '8': ['01110', '10001', '10001', '01110', '10001', '10001', '01110'],
    '9': ['01110', '10001', '10001', '01111', '00001', '00010', '01100'],
  };
  const BLANK = ['00000', '00000', '00000', '00000', '00000', '00000', '00000'];

  window.renderDots = function (el, text) {
    el.innerHTML = '';
    el.setAttribute('aria-label', text);
    el.classList.add('dots');
    for (const ch of String(text).slice(0, 4)) {
      const rows = FONT[ch] || BLANK;
      const g = document.createElement('div');
      g.className = 'dots-char';
      for (const row of rows) {
        for (const bit of row) {
          const d = document.createElement('i');
          if (bit === '1') d.className = 'on';
          g.appendChild(d);
        }
      }
      el.appendChild(g);
    }
  };
})();
